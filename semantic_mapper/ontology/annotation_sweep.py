"""
Provenance annotation sweep for OWL graphs.

Scans every OWL Class, DatatypeProperty, and ObjectProperty for missing
fm: provenance annotations and synthesises them from available evidence.
This is a safety net for ontologies that were not generated by the Phase 0b
iterative generator.

fm: namespace: http://forgemesh.ai/ontology#
  fm:sourceTable    — on owl:Class
  fm:sourceColumn   — on owl:DatatypeProperty  (table.column)
  fm:sqlType        — on owl:DatatypeProperty
  fm:nullRate       — on owl:DatatypeProperty  (0.00–1.00)
  fm:sourceForeignKey — on owl:ObjectProperty  (table.col -> target)

Synthesis priority (per element type):
  Class:
    1. SemanticMappingReport class_candidate_set → fm:sourceTable = source_table
    2. URI local name fallback

  DatatypeProperty:
    1. SemanticMappingReport column_mappings → fm:sourceColumn, fm:sqlType, fm:nullRate
    2. skos:altLabel hint → fm:sourceColumn = "unknown.{altLabel}"
    3. URI local name fallback

  ObjectProperty:
    1. SemanticMappingReport + range match → fm:sourceForeignKey = "table.col -> target"
    2. SemanticMappingReport without range → fm:sourceForeignKey = "table.col -> (target unknown)"
    3. Degraded → fm:sourceForeignKey = "not recoverable"

Synthesised annotations are logged at DEBUG; an ObjectProperty whose source FK
is not recoverable is logged at WARNING.
"""
from __future__ import annotations

import logging
from typing import Dict, Optional, Set, Tuple

import rdflib
from rdflib import OWL, RDF, RDFS, URIRef, Literal
from rdflib.namespace import SKOS

from dataclasses import dataclass

logger = logging.getLogger(__name__)

FM = rdflib.Namespace("http://forgemesh.ai/ontology#")

_SKOS_ALT = SKOS.altLabel


@dataclass
class AnnotationSweepResult:
    total_classes: int
    total_properties: int
    synthesised_classes: int
    synthesised_data_properties: int
    synthesised_object_properties: int
    unsynthesisable: int

    @property
    def synthesised_properties(self) -> int:
        """Combined count for backwards compatibility."""
        return self.synthesised_data_properties + self.synthesised_object_properties


def sweep_provenance_annotations(
    graph: rdflib.Graph,
    mapping_report=None,  # Optional[SemanticMappingReport]
) -> AnnotationSweepResult:
    """Add fm: provenance annotations to every class/property that lacks them.

    Args:
        graph:          Loaded rdflib.Graph (mutated in place).
        mapping_report: Optional SemanticMappingReport for richer synthesis.

    Returns:
        AnnotationSweepResult with per-type counts.
    """
    # Build lookup tables from mapping report
    class_sources: Dict[str, str] = {}
    prop_sources: Dict[str, Tuple[str, str, str]] = {}  # uri → (table, col, dtype)
    class_table_map: Dict[str, Set[str]] = {}  # table → set of class URIs

    if mapping_report is not None:
        for tm in mapping_report.tables:
            for cc in tm.class_candidate_set:
                if cc.uri:
                    if cc.uri not in class_sources:
                        class_sources[cc.uri] = tm.source_table
                    class_table_map.setdefault(tm.source_table, set()).add(cc.uri)
            for pm in tm.column_mappings:
                if pm.mapped_property_uri and pm.mapped_property_uri not in prop_sources:
                    prop_sources[pm.mapped_property_uri] = (
                        tm.source_table,
                        pm.source_column,
                        pm.source_data_type or "",
                    )

    classes = [s for s in graph.subjects(RDF.type, OWL.Class) if isinstance(s, URIRef)]
    data_props = [s for s in graph.subjects(RDF.type, OWL.DatatypeProperty) if isinstance(s, URIRef)]
    obj_props = [s for s in graph.subjects(RDF.type, OWL.ObjectProperty) if isinstance(s, URIRef)]

    synth_classes = synth_data = synth_obj = unsynthesisable = 0

    for cls in classes:
        if list(graph.objects(cls, FM.sourceTable)):
            continue
        uri_str = str(cls)
        if uri_str in class_sources:
            val = class_sources[uri_str]
        else:
            val = _local_name(uri_str) or "unknown"
        graph.add((cls, FM.sourceTable, Literal(val)))
        synth_classes += 1
        logger.warning(
            "annotation_sweep: synthesised fm:sourceTable for class <%s>: %s",
            uri_str, val,
        )

    for prop in data_props:
        uri_str = str(prop)
        missing_col = not list(graph.objects(prop, FM.sourceColumn))
        missing_type = not list(graph.objects(prop, FM.sqlType))
        missing_rate = not list(graph.objects(prop, FM.nullRate))
        if not (missing_col or missing_type or missing_rate):
            continue

        if uri_str in prop_sources:
            table, col, dtype = prop_sources[uri_str]
            col_val = f"{table}.{col}"
            type_val = dtype or "unknown"
            rate_val = "0.00"
        else:
            alt_labels = [str(o) for o in graph.objects(prop, _SKOS_ALT)]
            col_hint = alt_labels[0] if alt_labels else _local_name(uri_str)
            col_val = f"unknown.{col_hint}" if col_hint else "unknown.unknown"
            type_val = "unknown"
            rate_val = "unknown"

        if missing_col:
            graph.add((prop, FM.sourceColumn, Literal(col_val)))
        if missing_type:
            graph.add((prop, FM.sqlType, Literal(type_val)))
        if missing_rate:
            graph.add((prop, FM.nullRate, Literal(rate_val)))
        synth_data += 1
        logger.warning(
            "annotation_sweep: synthesised fm: data property annotations for <%s>",
            uri_str,
        )

    for prop in obj_props:
        if list(graph.objects(prop, FM.sourceForeignKey)):
            continue
        uri_str = str(prop)
        range_uris = [str(o) for o in graph.objects(prop, RDFS.range)]

        if uri_str in prop_sources:
            table, col, _ = prop_sources[uri_str]
            target_table = ""
            for rng_uri in range_uris:
                for t_table, class_uris in class_table_map.items():
                    if rng_uri in class_uris:
                        target_table = t_table
                        break
                if target_table:
                    break
            if target_table:
                val = f"{table}.{col} -> {target_table}"
            else:
                val = f"{table}.{col} -> (target unknown)"
        else:
            val = "not recoverable"

        graph.add((prop, FM.sourceForeignKey, Literal(val)))
        synth_obj += 1
        level = logging.WARNING if val == "not recoverable" else logging.DEBUG
        logger.log(
            level,
            "annotation_sweep: synthesised fm:sourceForeignKey for object property <%s>: %s",
            uri_str, val,
        )

    return AnnotationSweepResult(
        total_classes=len(classes),
        total_properties=len(data_props) + len(obj_props),
        synthesised_classes=synth_classes,
        synthesised_data_properties=synth_data,
        synthesised_object_properties=synth_obj,
        unsynthesisable=unsynthesisable,
    )


def remove_legacy_provenance_comments(graph: rdflib.Graph) -> int:
    """Remove any rdfs:comment triple whose value contains 'Derived from'.

    Returns the count of triples removed. Logs INFO for each removal.
    """
    to_remove = [
        (s, RDFS.comment, o)
        for s, _, o in graph.triples((None, RDFS.comment, None))
        if "Derived from" in str(o)
    ]
    for triple in to_remove:
        graph.remove(triple)
        logger.info(
            "annotation_sweep: removed legacy provenance rdfs:comment from <%s>", triple[0]
        )
    return len(to_remove)


def _local_name(uri_str: str) -> str:
    if "#" in uri_str:
        return uri_str.rsplit("#", 1)[-1]
    return uri_str.rsplit("/", 1)[-1]
