"""ProofPresentation — standardised presentation contract for agentic clients.

Sits on top of the raw proof records (v1 lineage + v2 semantic) and provides
an ordered, frozen, versioned view for agent rendering. Generated by
build_presentation(); never modify the underlying proof records.

Contract version: 1.0.0
Section order is guaranteed and must be preserved by renderers.
"""
from __future__ import annotations

from typing import Any, Dict, List, Literal, Optional

from pydantic import BaseModel


# ── Sub-models ────────────────────────────────────────────────────────────────

class PropertyTrace(BaseModel, frozen=True):
    """A property URI used in the query, with its local name."""

    uri: str
    local_name: str
    abstract_parent: Optional[str] = None  # reserved: rdfs:subPropertyOf traversal


class QueryDisplay(BaseModel, frozen=True):
    """The query that was executed, in human and machine form."""

    sparql: str
    plain_english_summary: str
    cache_status: Literal["fresh", "cached", "stale_ontology"]


class OntologyGrounding(BaseModel, frozen=True):
    """Ontology classes and properties referenced by the query."""

    classes_used: List[str]
    properties_used: List[PropertyTrace]


class LayerTrace(BaseModel, frozen=True):
    """A single table at one pipeline layer that contributed to the result."""

    layer: Literal["gold", "silver", "bronze"]
    table_name: str
    column_names: List[str]


class TransformationRecord(BaseModel, frozen=True):
    """One mapping decision from the semantic mapping report."""

    property_uri: str
    local_name: str
    confirmation: str
    score: Optional[float] = None
    rule_reference: Optional[str] = None  # winning_strategy from mapping decision


class ResultConfidence(BaseModel, frozen=True):
    """Quantitative confidence signals for the result."""

    row_count: int
    quarantined_row_count: int
    broken_lineage_count: int
    cache_hit: bool
    stale_ontology_warning: bool
    notes: List[str]


# ── Main contract ─────────────────────────────────────────────────────────────

class ProofPresentation(BaseModel, frozen=True):
    """Ordered, versioned presentation of a proof for agentic clients.

    Sections appear in a fixed order; renderers must preserve this order and
    must not omit sections. proof_presentation_version enables agents to detect
    breaking changes.
    """

    proof_presentation_version: str = "1.0.0"
    # Section 1 — NL interpretation
    question_interpretation: str
    # Section 2 — query display
    query_display: QueryDisplay
    # Section 3 — ontology grounding
    ontology_grounding: OntologyGrounding
    # Section 4 — data lineage trace
    data_layer_trace: List[LayerTrace]
    # Section 5 — transformation provenance
    transformation_provenance: List[TransformationRecord]
    # Section 6 — result confidence
    result_confidence: ResultConfidence
    # Section 7 — limitations (always last)
    limitations: List[str]


# ── Builder ───────────────────────────────────────────────────────────────────

def _local_name(uri: str) -> str:
    return uri.split("#")[-1].split("/")[-1]


def _build_question_interpretation(
    v2_proof: Optional[Dict[str, Any]],
    v1_proof_dict: Optional[Dict[str, Any]],
    nl_question: str,
) -> str:
    if v2_proof is not None:
        interp = v2_proof.get("interpretation") or {}
        confidence = interp.get("confidence", "")
        reason = interp.get("confidence_reason", "")
        concepts = interp.get("interpreted_concepts") or []
        if concepts:
            annotation = concepts[0].get("grounding_annotation", "")
            description = annotation if annotation else _local_name(
                concepts[0].get("mapped_to_uri", "")
            )
        else:
            description = "the queried concept"
        parts = [f'"{nl_question}" was interpreted as {description}']
        if confidence:
            parts.append(f"{confidence} confidence")
        if reason:
            parts.append(reason)
        return ", ".join(parts) + "."

    if v1_proof_dict is not None:
        v1_interp = v1_proof_dict.get("interpretation") or {}
        interpreted_as = v1_interp.get("interpreted_as", "")
        if interpreted_as:
            return interpreted_as
    return nl_question


def _build_ontology_grounding(
    v2_proof: Optional[Dict[str, Any]],
    executed_query: str,
) -> OntologyGrounding:
    if v2_proof is None:
        return OntologyGrounding(classes_used=[], properties_used=[])

    framing = v2_proof.get("framing") or {}
    primary = framing.get("primary_class_uri", "")
    joined = framing.get("joined_class_uris") or []
    classes_used = [c for c in ([primary] + list(joined)) if c]

    # Parse actual BGP predicates from the executed SPARQL — not the class-reachable
    # scope subgraph, which over-reports by including all ontology properties for the
    # queried classes regardless of whether they appear in the query.
    from semantic_mapper.rdf.proof.framing import _extract_prop_uris, expand_prefixes
    bgp_uris = _extract_prop_uris(expand_prefixes(executed_query)) if executed_query else []

    seen_prop_uris: set = set()
    prop_traces: List[PropertyTrace] = []
    for uri in bgp_uris:
        if uri and uri not in seen_prop_uris:
            seen_prop_uris.add(uri)
            prop_traces.append(PropertyTrace(uri=uri, local_name=_local_name(uri)))

    return OntologyGrounding(classes_used=classes_used, properties_used=prop_traces)


def _build_layer_trace(v1_proof_dict: Optional[Dict[str, Any]]) -> List[LayerTrace]:
    if v1_proof_dict is None:
        return []

    gold_cols: Dict[str, set] = {}
    silver_cols: Dict[str, set] = {}
    bronze_cols: Dict[str, set] = {}

    for chain in (v1_proof_dict.get("lineage") or []):
        gold = chain.get("gold") or {}
        if gold.get("table"):
            t = gold["table"]
            gold_cols.setdefault(t, set()).update((gold.get("row_values") or {}).keys())

        for s in (chain.get("silver") or []):
            if s.get("table"):
                t = s["table"]
                silver_cols.setdefault(t, set()).update((s.get("row_values") or {}).keys())

        for b in (chain.get("bronze") or []):
            if b.get("table"):
                t = b["table"]
                bronze_cols.setdefault(t, set()).update((b.get("raw_values") or {}).keys())

    traces: List[LayerTrace] = []
    for table, cols in sorted(gold_cols.items()):
        traces.append(LayerTrace(layer="gold", table_name=table, column_names=sorted(cols)))
    for table, cols in sorted(silver_cols.items()):
        traces.append(LayerTrace(layer="silver", table_name=table, column_names=sorted(cols)))
    for table, cols in sorted(bronze_cols.items()):
        traces.append(LayerTrace(layer="bronze", table_name=table, column_names=sorted(cols)))
    return traces


def _build_transformation_provenance(
    v1_proof_dict: Optional[Dict[str, Any]],
    used_property_uris: Optional[set] = None,
) -> List[TransformationRecord]:
    """Return mapping decisions scoped to the query's used property URIs.

    ISSUE-04: the old implementation returned all mapping_decisions for every
    property of every queried class (~130 entries). We now filter to only the
    property URIs that actually appear in the query's BGP, giving a tight,
    auditable list.  Three global limitations are emitted separately (see
    REQUIRED_LIMITATIONS); they are not repeated here.

    Args:
        v1_proof_dict: serialised ProofRecord from the /api/query/proof endpoint.
        used_property_uris: set of full URIs extracted from the executed query's
            BGP. When None (no filter available), all decisions are returned to
            preserve backward compatibility.
    """
    if v1_proof_dict is None:
        return []
    records: List[TransformationRecord] = []
    for d in sorted(v1_proof_dict.get("mapping_decisions") or [], key=lambda x: x.get("uri", "")):
        uri = d.get("uri", "")
        # Filter to used set when available (ISSUE-04).
        if used_property_uris is not None and uri and uri not in used_property_uris:
            continue
        score_raw = d.get("score")
        records.append(TransformationRecord(
            property_uri=uri,
            local_name=_local_name(uri),
            confirmation=d.get("confirmation", ""),
            score=float(score_raw) if score_raw is not None else None,
            rule_reference=d.get("winning_strategy") or None,
        ))
    return records


def _build_result_confidence(
    v2_proof: Optional[Dict[str, Any]],
    v1_proof_dict: Optional[Dict[str, Any]],
    query_row_count: Optional[int] = None,
) -> ResultConfidence:
    row_count = 0
    if v2_proof is not None:
        row_count = (v2_proof.get("framing") or {}).get("cardinality", 0)
    elif query_row_count is not None:
        # ISSUE-06: gold/silver proofs have no v2_proof, so fall back to the
        # actual rows the query returned rather than subject_count (which is the
        # number of gold subjects scanned, not the number of result rows).
        row_count = query_row_count
    elif v1_proof_dict is not None:
        row_count = v1_proof_dict.get("subject_count", 0)

    quarantined = 0
    broken = 0
    notes: List[str] = []

    if v1_proof_dict is not None:
        for c in (v1_proof_dict.get("caveats") or []):
            if c.get("type") == "QUARANTINED":
                quarantined += c.get("count") or 0
            elif c.get("type"):
                note = c.get("type", "")
                if c.get("count") is not None:
                    note += f" (count={c['count']})"
                if c.get("reason"):
                    note += f": {c['reason']}"
                notes.append(note)
        for chain in (v1_proof_dict.get("lineage") or []):
            if chain.get("broken"):
                broken += 1

    return ResultConfidence(
        row_count=row_count,
        quarantined_row_count=quarantined,
        broken_lineage_count=broken,
        cache_hit=False,
        stale_ontology_warning=False,
        notes=notes,
    )


def _build_limitations(
    v2_proof: Optional[Dict[str, Any]],
    v1_proof_dict: Optional[Dict[str, Any]],
) -> List[str]:
    seen: set = set()
    texts: List[str] = []

    if v2_proof is not None:
        for lim in (v2_proof.get("limitations") or []):
            t = lim.get("text", "")
            if t and t not in seen:
                seen.add(t)
                texts.append(t)

    if v1_proof_dict is not None:
        for lim in (v1_proof_dict.get("limitations") or []):
            if lim and lim not in seen:
                seen.add(lim)
                texts.append(lim)

    return texts


def build_presentation(
    v2_proof: Optional[Dict[str, Any]],
    v1_proof_dict: Optional[Dict[str, Any]],
    executed_query: str,
    nl_question: str,
    query_row_count: Optional[int] = None,
) -> ProofPresentation:
    """Build a ProofPresentation from available proof data.

    v2_proof and v1_proof_dict may each be None; the builder degrades gracefully.
    Never raises — returns a minimal-but-valid ProofPresentation on any error.

    Args:
        query_row_count: actual rows returned by the query (for gold/silver mode
            where v2_proof is absent and subject_count would over-report).
    """
    question_interp = _build_question_interpretation(v2_proof, v1_proof_dict, nl_question)
    query_display = QueryDisplay(
        sparql=executed_query,
        plain_english_summary=nl_question,
        cache_status="fresh",
    )
    ontology_grounding = _build_ontology_grounding(v2_proof, executed_query)
    # Extract BGP property URIs for ISSUE-04 used-set filtering.
    # Only apply the filter when the BGP parser found at least one URI — an empty
    # set means the query is SQL (no angle-bracket URIs) or could not be parsed,
    # in which case we pass None so _build_transformation_provenance returns all
    # decisions rather than nothing.
    _bgp_prop_uris: Optional[set] = (
        {pt.uri for pt in ontology_grounding.properties_used} or None
    )
    layer_trace = _build_layer_trace(v1_proof_dict)
    transformation_provenance = _build_transformation_provenance(v1_proof_dict, _bgp_prop_uris)
    result_confidence = _build_result_confidence(v2_proof, v1_proof_dict, query_row_count)
    limitations = _build_limitations(v2_proof, v1_proof_dict)

    return ProofPresentation(
        question_interpretation=question_interp,
        query_display=query_display,
        ontology_grounding=ontology_grounding,
        data_layer_trace=layer_trace,
        transformation_provenance=transformation_provenance,
        result_confidence=result_confidence,
        limitations=limitations,
    )
